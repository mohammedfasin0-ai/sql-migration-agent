import os

from dotenv import load_dotenv
from groq import Groq

from migration_task import MigrationTask


load_dotenv()


class LLMTranslator:

    def __init__(self):
        self.client = Groq(
            api_key=os.environ["GROQ_API_KEY"]
        )

        def translate(self, task: MigrationTask) -> str:
            prompt = f"""
    Convert the following SQL from Oracle to PostgreSQL.

    Source dialect: {task.source_dialect}
    Target dialect: {task.target_dialect}

    Relevant database schema:
    {task.relevant_schema}

    Original SQL:
    {task.original_sql}

    Return only the converted PostgreSQL SQL.
    Do not explain your answer.
    """

            response = self.client.chat.completions.create(
                model="openai/gpt-oss-20b",
                messages=[
                    {
                        "role": "system",
                        "content": (
                            "You are an expert database migration engineer. "
                            "Convert Oracle SQL to PostgreSQL accurately."
                        ),
                    },
                    {
                        "role": "user",
                        "content": prompt,
                    },
                ],
            )

            return response.choices[0].message.content

        def repair_schema(self, postgres_ddl: str, error: str) -> str:
            """Repair PostgreSQL DDL rejected by the database."""

            prompt = f"""
    The following PostgreSQL DDL was generated by a deterministic
    Oracle-to-PostgreSQL translator, but PostgreSQL rejected it.

    DDL:
    {postgres_ddl}

    Exact PostgreSQL error:
    {error}

    Your task:
    1. Identify the likely cause of the error.
    2. Make the smallest correction that preserves the intended schema.
    3. Return the complete corrected DDL.
    4. Return only CREATE TABLE statements.
    5. Do not add sample data, explanations, or Markdown fences.
    6. Do not invent unrelated tables or columns.

    Return only the corrected PostgreSQL DDL.
    """

            response = self.client.chat.completions.create(
                model="openai/gpt-oss-20b",
                messages=[
                    {
                        "role": "system",
                        "content": (
                            "You repair PostgreSQL DDL. Return SQL only. "
                            "Never return DROP, ALTER, INSERT, UPDATE, "
                            "DELETE, or other statements unrelated to "
                            "creating the supplied tables."
                        ),
                    },
                    {
                        "role": "user",
                        "content": prompt,
                    },
                ],
                temperature=0,
            )

            repaired_ddl = response.choices[0].message.content

            if not repaired_ddl or not repaired_ddl.strip():
                raise ValueError("The LLM returned empty repaired DDL.")

            return repaired_ddl.strip()